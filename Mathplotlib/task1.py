import matplotlib.pyplot as plt

# 1. Створюємо списки місяців і значень
months = ['Січень', 'Лютий', 'Березень', 'Квітень', 'Травень', 'Червень']
plan = [100, 120, 130, 150, 170, 200]
fact = [95, 125, 120, 160, 165, 210]

# 2. Побудова графіка з двома лініями
plt.figure(figsize=(8, 5))
plt.plot(months, plan, label='План', marker='o', linestyle='--', color='blue')
plt.plot(months, fact, label='Факт', marker='s', linestyle='-', color='green')

# 3. Додаємо підписи осей, заголовок та легенду
plt.title('Порівняння планових і фактичних продажів', fontsize=14)
plt.xlabel('Місяці', fontsize=12)
plt.ylabel('Продажі (од.)', fontsize=12)
plt.legend()

# Додаємо сітку для зручності читання
plt.grid(True, linestyle=':', alpha=0.6)

# 4. Відображення графіка
plt.show()